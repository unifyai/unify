"""Global builtin-guidance catalogue: stable ids and idempotent seeding.

The catalogue lives in the public-read builtins project (see
``unify.common.builtins``) owned by the platform admin account. It stores
exactly one platform-wide copy of every builtin guidance entry; every
tenant reads it by default and never writes to it.

Two sources feed the default seeding set:

* the committed snapshot ``builtins_guidance.json`` next to this module,
  generated by ``scripts.skill_migration.builtins_import`` from upstream
  Agent Skills repositories pinned in a lockfile manifest, and
* ``PLATFORM_GUIDANCE_ENTRIES`` below — platform-authored entries versioned
  directly in code (kept out of the snapshot so importer regeneration can
  never drop them).

Seeding is hash-guarded per entry: only changed or removed entries are
deleted and re-inserted, so repeated runs are cheap and idempotent.

Builtin rows carry stable hash-based ``guidance_id`` values (derived from
the namespaced title) so they never collide semantically with tenant
auto-counting ids, and ``is_builtin=True`` for unambiguous provenance.
"""

from __future__ import annotations

import hashlib
import json
import logging
from pathlib import Path
from typing import Dict, List, Optional

from unify import db
from unify.db import StoreError
from ..common.builtins import (
    builtins_project,
    ensure_builtins_project,
    read_seed_hashes,
    write_seed_hashes,
)
from ..common.embed_utils import ensure_vector_column
from ..common.model_to_fields import model_to_fields
from .types.guidance import Guidance

logger = logging.getLogger(__name__)

BUILTINS_GUIDANCE_CONTEXT = "Guidance"
BUILTINS_GUIDANCE_META_CONTEXT = "Guidance/Meta"
_HASH_MAP_KEY = "guidance_hash_by_skill"

# The backend refuses to embed inputs above ~8000 estimated tokens (0.25 per
# UTF-8 byte, i.e. ~32KB). Imported skills with inlined scripts routinely
# exceed that, so the content embedding ranks on a truncated head of the
# entry — where the description and body intro carry the retrieval signal —
# while the stored ``content`` column keeps the full text.
CONTENT_EMBED_HEAD_CHARS = 24000

SNAPSHOT_PATH = Path(__file__).with_name("builtins_guidance.json")

_MANAGER_ROUTING_CONTENT = """\
Which state manager to use when two overlap: `primitives.data` vs
`primitives.files`, and data vs `primitives.ingestion` (reading vs storing).

CRITICAL: `primitives.data.*` vs `primitives.files.*` — these serve
DIFFERENT purposes, do not confuse them:
- `primitives.data.*`: ALL analytical and data operations — filtering,
  searching, aggregating, joining. Works on any Unify context (`Data/*`,
  `Files/*`, `Knowledge/*`). Use when the question is about DATA INSIDE
  tables, regardless of where those tables came from. Always prefer
  server-side `filter=` / `reduce` / join variants over fetching rows into
  Python loops.
- `primitives.files.*`: file-specific operations — describing the storage
  layout of an uploaded/received file, listing files in the file registry,
  parsing documents, rendering PDFs/Excel sheets as images for visual
  inspection. Use when the question is about FILES themselves (metadata,
  layout, parsing) or when you need file-path-based context resolution.
  (Worked examples at the end.)

Reading vs storing: `primitives.data.*` vs `primitives.ingestion.*`
- `data` reads and reshapes what is already stored (filter, search, reduce,
  join, update_rows). STORING new data is not data's job: anything that puts
  NEW data somewhere queryable — API responses, connected-app pulls, files,
  folders, table reshapes — goes through `primitives.ingestion.submit`.
- If an ingestion run fails, read `get_logs(run_id)`, fix the cause, and
  submit again. Do not store the data another way (`create_table` +
  `insert_rows`, hand-written loops): those write rows nothing checkpoints,
  verifies against a declared count, or can resume, so a part-way failure
  leaves a table that looks complete. Report the limitation instead.

Manager selection priorities (when in doubt, the most specific domain wins):
1. `transcripts` for historical communications (what was said/written)
2. `contacts` for people/relationship information
3. `tasks` for work items, deadlines, assignments
4. `web` for current external information (weather, news, real-time data)
5. `files` when dealing with specific documents or file-level operations
6. `data` for tabular contexts (`Data/*` and other tables):
   filter, reduce, join, update_rows — never client-scan large tables in
   Python

Typed claim / procedure catalogues (`KnowledgeManager_*`,
`GuidanceManager_*`) are top-level Actor JSON tools, not `primitives.*` —
use them for durable domain claims and SOPs.

Worked examples (data vs files):
- "What tables exist under Data/examplehousing?" ->
  `primitives.data.list_tables(prefix=...)` (data)
- "Describe the schema of the repairs table" ->
  `primitives.data.describe_table(...)` (data)
- "What's in the uploaded PDF?" ->
  `primitives.files.describe(file_path=...)` (files)
- "Render page 3 of the report as an image" ->
  `primitives.files.render_pdf(...)` (files)
"""

_DURABLE_TASKS_CONTENT = """\
How to create, verify, arm, and run durable tasks — work that happens
later, repeatedly, or on future inbound messages: schedules, recurring
cadences, communication triggers, offline jobs.

Operative contract
- Create and edit through the text-driven mutation loop:
  `primitives.tasks.update(text)` handles ALL durable task mutations,
  including one-shot creates and field edits. Example:

      await primitives.tasks.update(
          'Create a live task named Weekly digest (marketing) with '
          'description Summarize the week and email it to Dana, '
          'repeating every Monday at 09:00 UTC.'
      )

- Armed vs draft: a task only fires while armed — `enabled=True` plus a
  resolved `schedule.start_at` or trigger. A draft NEVER fires. Say
  "live"/"armed" in the create text rather than leaving a draft.
- MANDATORY post-create verification: after every create, call
  `primitives.tasks.ask(...)` and confirm (1) the exact fields, (2) it
  is armed (`enabled=True`), and (3) trigger bindings resolved — a
  communication trigger needs named senders resolved to contact ids.
- Verbatim copy: quoted task names, descriptions, and reference tokens
  (`Ref: TASK-…`) are matched exactly — copy them verbatim, including
  punctuation and parenthetical suffixes; creates reject duplicates,
  and verification and later lookups depend on the literal string.
- `primitives.tasks.execute(task_id)` runs one instance now: a
  contained child actor interprets the task; returns a steerable handle.

Task model and taxonomy
A definition row carries authored intent only; every wake is projected by
the scheduler into a `Tasks/Executions` run row, where run state and
outcomes live. `schedule` and `trigger` are mutually exclusive on one task.
- scheduled: `schedule.start_at` (ISO-8601) with no `repeat` and no
  `trigger` — a one-shot. After it runs it is disarmed and can never be
  re-armed; create a new task instead of re-running it.
- recurring: `schedule` plus `repeat` patterns (minutely/hourly for
  sub-daily intervals; daily/weekly/monthly/yearly for calendar
  cadences). The successor occurrence is projected by the scheduler
  when a run is marked running — recurrence is a ledger invariant, and
  the definition stays armed across runs.
- triggered (communication): `trigger.kind="communication"` names the
  `medium` (`unify_message`) with optional `from_contact_ids` /
  `omit_contact_ids` filters and a `recurring` flag (True returns the
  task to the triggerable state after each completion).
- offline is a delivery lane, not a task type: `offline=True` runs in
  the hidden headless lane without the live assistant runtime, so the
  run is not steerable from chat. Do not mark tasks offline unless
  asked.
- `deadline` is a calendar due date; `start_at` is when work should
  begin; `max_runtime_seconds` bounds one attempt's wall clock. For
  short predictable work set only `start_at`. `priority` is
  low|normal|high|urgent; `tags` carry no scheduling semantics.
- `enabled=False` disarms everything: schedules and triggers do not
  activate, and manual execute is rejected until re-enabled.

Update semantics (`update_task`)
- Only provided fields change. `start_at`/`deadline`/`repeat`/`trigger`
  distinguish omitted from explicit None: None clears the field, and
  clearing the schedule sweeps `repeat` with it unless a new repeat is
  set in the same call. Convert scheduled→triggered in one call:
  `trigger=..., start_at=None`.
- Deployment-owned tasks (`custom_hash` set, deployment-managed) refuse
  runtime edits of authored fields — edit the source definition and
  re-sync.

Binding resolution in depth
- Communication triggers: resolve named senders to contact ids before
  creating — `from_contact_ids` is a list of contact ids, and a filter
  that never got resolved to ids cannot match. Unset matches any
  sender; `omit_contact_ids` overrides.

Entrypoint vs description-driven execution
- Default to description-driven: `entrypoint=None` makes the task
  agentic — the due wake calls `primitives.tasks.execute(task_id=...)`
  and a contained child actor interprets the name, description, and
  metadata. Put the operative context into the description.
- Do not attach an untested entrypoint at creation. Entrypoint
  persistence should follow an explicit user request or a successful
  run reviewed as stable enough to store; the stored function then earns
  trust from independent verification, and offline promotion follows once
  every function it calls is trusted.
- Stored entrypoints: prefer `async def` + `await`; never nest
  `asyncio.run(...)` (offline Jobs already own the loop — use
  `run_coro_sync` for a sync façade); keep expressive stdlib `logging`
  PHASE/SKIP/SOFT_FAIL trails so soft outcomes (empty results, skips,
  degraded fallbacks) leave evidence; focused `query_llm(...)` calls for
  bounded semantic judgment are fine.

Execution guards (`execute`)
- Rejected: disabled tasks, one-shots that already ran, a task invoking
  its own task_id within its execution chain, and a wake targeting an
  instance that is already active. Concurrent instances of the same
  task_id from distinct wakes are allowed — serialize in the entrypoint
  if needed.
"""

PLATFORM_GUIDANCE_ENTRIES: Dict[str, Dict[str, str]] = {
    "platform/manager-routing": {
        "title": (
            "[platform] Choosing between overlapping state managers: data vs "
            "files vs ingestion"
        ),
        "content": _MANAGER_ROUTING_CONTENT,
    },
    "platform/durable-tasks": {
        "title": (
            "[platform] Durable tasks: creating, verifying, arming, and "
            "running scheduled and triggered tasks"
        ),
        "content": _DURABLE_TASKS_CONTENT,
    },
}


def default_guidance_entries() -> Dict[str, Dict[str, str]]:
    """The full default seeding set: imported skills + platform entries."""
    return {**load_snapshot(), **PLATFORM_GUIDANCE_ENTRIES}


def stable_guidance_id(title: str) -> int:
    """Derive the stable builtin guidance id from a namespaced title.

    First 4 bytes of SHA-256, masked to the signed int32 range so backend
    integer sorting never overflows (mirrors primitive function ids).
    """
    digest = hashlib.sha256(title.encode("utf-8")).digest()
    return int.from_bytes(digest[:4], "big") & 0x7FFFFFFF


def entry_hash(title: str, content: str) -> str:
    """Content hash guarding per-skill reseeding."""
    return hashlib.sha256(f"{title}\x00{content}".encode("utf-8")).hexdigest()[:16]


def load_snapshot(path: Optional[Path] = None) -> Dict[str, Dict[str, str]]:
    """Load the committed builtins guidance snapshot (skill key → entry).

    Returns an empty mapping when the snapshot has not been generated yet.
    """
    path = path or SNAPSHOT_PATH
    if not path.exists():
        return {}
    data = json.loads(path.read_text(encoding="utf-8"))
    return data.get("skills", {})


def _ensure_catalog_storage(project: str) -> None:
    """Create the catalogue project and contexts (idempotent).

    The context is created without the per-assistant Guidance foreign keys
    (cross-project FKs do not exist); builtin entries have empty ``images``
    and ``function_ids``.
    """
    ensure_builtins_project(project)
    db.create_context(
        BUILTINS_GUIDANCE_CONTEXT,
        description="Builtin procedural guidance imported from the Agent Skills ecosystem.",
        unique_keys={"guidance_id": "int"},
        project=project,
    )
    # Pre-create the model schema so federated reads (from_fields
    # projections) are well-defined even before the first rows land.
    db.create_fields(
        model_to_fields(Guidance),
        context=BUILTINS_GUIDANCE_CONTEXT,
        project=project,
    )
    db.create_context(
        BUILTINS_GUIDANCE_META_CONTEXT,
        description="Seeding state for the builtin guidance catalogue.",
        unique_keys={"meta_id": "int"},
        project=project,
    )


def _delete_rows_by_ids(project: str, guidance_ids: List[int]) -> None:
    if not guidance_ids:
        return
    ids_expr = ", ".join(str(gid) for gid in sorted(set(guidance_ids)))
    logs = db.get_logs(
        project=project,
        context=BUILTINS_GUIDANCE_CONTEXT,
        filter=f"guidance_id in [{ids_expr}]",
        return_ids_only=True,
    )
    if logs:
        db.delete_logs(
            project=project,
            context=BUILTINS_GUIDANCE_CONTEXT,
            logs=logs,
        )


def _guidance_diff(
    project: str,
    desired: Dict[str, Dict[str, object]],
) -> tuple[List[str], List[str], Dict[str, Dict[str, object]]]:
    """Read-only diff of the stored guidance hashes against *desired*.

    Returns ``(changed_keys, removed_keys, current)``. Reads only, so it runs
    for any principal that can read the public Builtins project. Raises when the
    catalogue storage is absent (fresh project).
    """
    current = read_seed_hashes(
        project,
        meta_context=BUILTINS_GUIDANCE_META_CONTEXT,
        key=_HASH_MAP_KEY,
    )
    changed = [
        skill_key
        for skill_key, state in desired.items()
        if (current.get(skill_key) or {}).get("hash") != state["hash"]
    ]
    removed = [skill_key for skill_key in current if skill_key not in desired]
    return changed, removed, current


def _insert_entries(project: str, entries: List[Dict[str, str]]) -> None:
    if not entries:
        return
    rows = [
        Guidance(
            guidance_id=stable_guidance_id(entry["title"]),
            title=entry["title"],
            content=entry["content"],
            is_builtin=True,
        ).model_dump(mode="json")
        for entry in entries
    ]
    db.create_logs(
        project=project,
        context=BUILTINS_GUIDANCE_CONTEXT,
        entries=rows,
        recompute_derived=True,
    )


def seed_builtin_guidance(
    *,
    project: Optional[str] = None,
    entries: Optional[Dict[str, Dict[str, str]]] = None,
) -> bool:
    """Seed the global builtins guidance catalogue from the snapshot.

    Idempotent and hash-guarded per skill: only skills whose title/content
    changed (or disappeared from the snapshot) are deleted and re-inserted,
    with ``recompute_derived=True`` so embeddings recompute only for written
    rows. Always ensures the ``content`` and ``title`` vector columns exist
    when the catalogue has rows, so read-only consumers can run ranked
    semantic search without any write access.

    Returns True when any rows were written or removed, False when already
    up to date.
    """
    project = project or builtins_project()
    entries = entries if entries is not None else default_guidance_entries()
    desired = {
        skill_key: {
            "hash": entry_hash(entry["title"], entry["content"]),
            "guidance_id": stable_guidance_id(entry["title"]),
        }
        for skill_key, entry in entries.items()
    }

    logger.info(
        "Starting builtins guidance catalogue seed project=%s skills=%d",
        project,
        len(entries),
    )

    # Read-only convergence probe (see seed_builtin_primitives): public-read
    # Builtins lets any principal verify convergence; an already-seeded
    # catalogue is a no-op. A missing catalogue raises and falls through to the
    # owner seed path.
    try:
        changed_keys, removed_keys, current = _guidance_diff(project, desired)
        storage_ready = True
    except StoreError:
        storage_ready = False

    if storage_ready and not changed_keys and not removed_keys:
        logger.info(
            "Builtins guidance catalogue already converged project=%s skills=%d; "
            "read-only no-op",
            project,
            len(entries),
        )
        return False

    _ensure_catalog_storage(project)
    if not storage_ready:
        changed_keys, removed_keys, current = _guidance_diff(project, desired)

    if changed_keys or removed_keys:
        stale_ids = [
            (current.get(skill_key) or {}).get("guidance_id")
            for skill_key in changed_keys + removed_keys
        ]
        stale_ids = [gid for gid in stale_ids if gid is not None]
        stale_ids.extend(
            desired[skill_key]["guidance_id"] for skill_key in changed_keys
        )
        _delete_rows_by_ids(project, stale_ids)
        _insert_entries(project, [entries[skill_key] for skill_key in changed_keys])
        write_seed_hashes(
            project,
            desired,
            meta_context=BUILTINS_GUIDANCE_META_CONTEXT,
            key=_HASH_MAP_KEY,
        )
        logger.info(
            "Seeded builtins guidance project=%s changed=%d removed=%d",
            project,
            len(changed_keys),
            len(removed_keys),
        )
    else:
        logger.info(
            "Builtins guidance catalogue already up to date project=%s skills=%d; "
            "skipping row rewrites",
            project,
            len(entries),
        )

    if desired:
        logger.info("Ensuring builtins guidance embedding columns project=%s", project)
        ensure_vector_column(
            BUILTINS_GUIDANCE_CONTEXT,
            embed_column="_content_emb",
            source_column="_content_head",
            derived_expr=f"str({{content}})[:{CONTENT_EMBED_HEAD_CHARS}]",
            project=project,
        )
        ensure_vector_column(
            BUILTINS_GUIDANCE_CONTEXT,
            embed_column="_title_emb",
            source_column="title",
            project=project,
        )
    return bool(changed_keys or removed_keys)


